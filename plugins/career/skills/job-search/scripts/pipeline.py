#!/usr/bin/env python3
"""Validate a job-search workspace and regenerate its pipeline.md. Standard library only.

Usage:
  python3 pipeline.py <workspace> --check     validate statuses and required fields, exit 1 on errors
  python3 pipeline.py <workspace> --write     validate, then rewrite <workspace>/pipeline.md
  python3 pipeline.py --self-test

Reads the top-level frontmatter of leads/*.md and applications/*/application.md. The dashboard is generated
by this script, never by hand or by a model, so it can't drift from the files.
"""

from __future__ import annotations

import argparse
import re
import sys
import tempfile
from datetime import date
from pathlib import Path

LEAD_STATUSES = ["new", "shortlisted", "rejected"]
APP_STATUSES = ["preparing", "applied", "screening", "interviewing", "offer",
                "accepted", "declined", "rejected", "withdrawn", "ghosted"]
ACTIVE = {"preparing", "applied", "screening", "interviewing", "offer"}
AFTER_APPLYING = {"applied", "screening", "interviewing", "offer", "accepted"}
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def frontmatter(path: Path) -> dict[str, str]:
    """Top-level scalar keys only; nested blocks (contacts) are ignored."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return {}
    block = text[4:].split("\n---", 1)[0]
    out = {}
    for line in block.splitlines():
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if m:
            out[m.group(1)] = m.group(2).strip().strip('"').strip("'")
    return out


def load(ws: Path) -> tuple[list[dict], list[dict], list[str]]:
    errors, leads, apps = [], [], []
    for p in sorted((ws / "leads").glob("*.md")):
        fm = frontmatter(p)
        fm["_path"] = p.relative_to(ws).as_posix()
        if fm.get("status") not in LEAD_STATUSES:
            errors.append(f"{fm['_path']}: status '{fm.get('status')}' not in {LEAD_STATUSES}")
        leads.append(fm)
    for p in sorted((ws / "applications").glob("*/application.md")):
        fm = frontmatter(p)
        fm["_path"] = p.relative_to(ws).as_posix()
        status = fm.get("status")
        if status not in APP_STATUSES:
            errors.append(f"{fm['_path']}: status '{status}' not in {APP_STATUSES}")
        for key in ("company", "role"):
            if not fm.get(key):
                errors.append(f"{fm['_path']}: '{key}' is required")
        for key in ("applied_on", "next_action_due"):
            if fm.get(key) and not DATE_RE.match(fm[key]):
                errors.append(f"{fm['_path']}: '{key}' must be YYYY-MM-DD, got '{fm[key]}'")
        if status in AFTER_APPLYING and not fm.get("applied_on"):
            errors.append(f"{fm['_path']}: status '{status}' needs applied_on")
        apps.append(fm)
    return leads, apps, errors


def render(leads: list[dict], apps: list[dict], today: date) -> str:
    lines = ["# Pipeline", "", f"<!-- Generated by job-search/scripts/pipeline.py on {today.isoformat()}. Don't edit by hand. -->", ""]
    active = sorted((a for a in apps if a.get("status") in ACTIVE), key=lambda a: a.get("next_action_due") or "9999")
    lines += ["## Active applications", ""]
    if active:
        lines += ["| Company | Role | Status | Next action | Due |", "|---|---|---|---|---|"]
        for a in active:
            due = a.get("next_action_due", "")
            flag = " ⚠️ overdue" if due and due < today.isoformat() else ""
            lines.append(f"| {a.get('company','')} | {a.get('role','')} | {a.get('status','')} | {a.get('next_action','')} | {due}{flag} |")
    else:
        lines.append("None.")
    waiting = [l for l in leads if l.get("status") in ("new", "shortlisted")]
    lines += ["", "## Leads awaiting a decision", ""]
    if waiting:
        lines += ["| Status | Company | Role | Found |", "|---|---|---|---|"]
        lines += [f"| {l.get('status','')} | {l.get('company','')} | {l.get('role','')} | {l.get('found_on','')} |" for l in waiting]
    else:
        lines.append("None.")
    counts = {s: n for s in APP_STATUSES if (n := sum(1 for a in apps if a.get("status") == s))}
    lines += ["", "## Counts", ""]
    if counts:
        lines += ["| Status | Count |", "|---|---|"] + [f"| {s} | {n} |" for s, n in counts.items()]
    else:
        lines.append("No applications yet.")
    lines += ["", f"Leads: {len(leads)} total, {len(waiting)} awaiting a decision. "
                  f"Applications: {len(apps)} total, {len(active)} active."]
    return "\n".join(lines) + "\n"


def self_test() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        ws = Path(tmp)
        (ws / "leads").mkdir()
        (ws / "applications" / "2026-10-01-acme-data-engineer").mkdir(parents=True)
        (ws / "applications" / "2026-10-02-bad").mkdir(parents=True)
        (ws / "leads" / "2026-10-03-zeta-analytics.md").write_text("---\nstatus: new\ncompany: Zeta\nrole: Analytics Engineer\nfound_on: 2026-10-03\n---\n")
        (ws / "applications" / "2026-10-01-acme-data-engineer" / "application.md").write_text(
            "---\nstatus: applied\ncompany: Acme\nrole: Data Engineer\napplied_on: 2026-10-01\nnext_action: follow up\n"
            "next_action_due: 2026-10-08\ncontacts:\n  - name: Jo\n---\n## Log\n")
        (ws / "applications" / "2026-10-02-bad" / "application.md").write_text("---\nstatus: sent\ncompany: Bad\n---\n")
        leads, apps, errors = load(ws)
        md = render(leads, apps, date(2026, 10, 13))
        checks = [len(leads) == 1, len(apps) == 2,
                  any("status 'sent'" in e for e in errors), any("'role' is required" in e for e in errors),
                  "| Acme | Data Engineer | applied | follow up | 2026-10-08 ⚠️ overdue |" in md,
                  "| new | Zeta | Analytics Engineer | 2026-10-03 |" in md]
    print("pipeline self-test:", "ok" if all(checks) else f"FAILED {checks}\n{errors}\n{md}")
    return 0 if all(checks) else 1


def main() -> int:
    ap = argparse.ArgumentParser(description="Validate a job-search workspace and regenerate pipeline.md.")
    ap.add_argument("workspace", nargs="?", type=Path)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    if args.self_test:
        return self_test()
    if not args.workspace:
        ap.error("give the workspace folder")
    leads, apps, errors = load(args.workspace)
    for e in errors:
        print(f"error: {e}")
    if args.write and not errors:
        (args.workspace / "pipeline.md").write_text(render(leads, apps, date.today()), encoding="utf-8")
        print(f"wrote {args.workspace / 'pipeline.md'}")
    print(f"{'FAILED' if errors else 'ok'}: {len(leads)} leads, {len(apps)} applications, {len(errors)} errors")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
