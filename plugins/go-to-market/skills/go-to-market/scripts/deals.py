#!/usr/bin/env python3
"""Validate a go-to-market workspace's deal files and regenerate its pipeline.md. Standard library only.

Usage:
  python3 deals.py <workspace> --check     validate stages, sources and required fields, exit 1 on errors
  python3 deals.py <workspace> --write     validate, then rewrite <workspace>/pipeline.md
  python3 deals.py --self-test

Reads the top-level frontmatter of deals/*.md, and quarter_target and currency from product.md.
The dashboard is generated by this script, never by hand or by a model, so it can't drift from the files.
"""

from __future__ import annotations

import argparse
import re
import sys
import tempfile
from datetime import date
from pathlib import Path

STAGES = ["lead", "qualified", "discovery", "proposal", "negotiation", "won", "lost", "parked"]
OPEN = ["lead", "qualified", "discovery", "proposal", "negotiation"]
PROBABILITY = {"lead": 5, "qualified": 10, "discovery": 25, "proposal": 50, "negotiation": 75}
NEEDS_VALUE = {"discovery", "proposal", "negotiation", "won"}
SOURCES = ["warm intro", "inbound", "outbound", "event", "referral", "partner", "community"]
LOSS_REASONS = ["price", "timing", "no decision", "competitor", "fit", "other"]
TIERS = ["A", "B", "C"]
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
STALE_DAYS = 14
SYMBOLS = {"EUR": "€", "USD": "$", "GBP": "£"}


def frontmatter(path: Path) -> dict[str, str]:
    """Top-level scalar keys only. Trailing '# comments' are dropped, so templates can carry hints."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return {}
    block = text[4:].split("\n---", 1)[0]
    out = {}
    for line in block.splitlines():
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if m:
            value = re.sub(r"(^|\s+)#\s.*$", "", m.group(2))
            out[m.group(1)] = value.strip().strip('"').strip("'")
    return out


def number(text: str | None) -> float | None:
    try:
        return float(text.replace(",", "").replace("_", ""))
    except (AttributeError, ValueError):
        return None


def problems(fm: dict[str, str]) -> list[str]:
    out = []
    stage = fm.get("stage")
    if stage not in STAGES:
        out.append(f"stage '{stage}' not in {STAGES}")
    if not fm.get("company"):
        out.append("'company' is required")
    if fm.get("source") not in SOURCES:
        out.append(f"source '{fm.get('source')}' not in {SOURCES}")
    if not fm.get("updated"):
        out.append("'updated' is required (YYYY-MM-DD)")
    for key in ("close_date", "next_step_due", "updated"):
        if fm.get(key) and not DATE_RE.match(fm[key]):
            out.append(f"'{key}' must be YYYY-MM-DD, got '{fm[key]}'")
    if stage in OPEN:
        out += [f"open deals need '{key}'" for key in ("next_step", "next_step_due") if not fm.get(key)]
    if stage == "parked" and not fm.get("next_step_due"):
        out.append("parked deals need 'next_step_due' (when to revisit)")
    if fm.get("value") and number(fm["value"]) is None:
        out.append(f"'value' must be a number, got '{fm['value']}'")
    elif stage in NEEDS_VALUE and not fm.get("value"):
        out.append(f"stage '{stage}' needs 'value'")
    if stage == "lost" and fm.get("loss_reason") not in LOSS_REASONS:
        out.append(f"lost deals need 'loss_reason' in {LOSS_REASONS}")
    if fm.get("probability"):
        p = number(fm["probability"])
        if p is None or not 0 <= p <= 100:
            out.append("'probability' must be 0-100")
    if fm.get("icp_tier") and fm["icp_tier"] not in TIERS:
        out.append(f"icp_tier '{fm['icp_tier']}' not in {TIERS}")
    return out


def load(ws: Path) -> tuple[list[dict], dict, list[str]]:
    deals, errors = [], []
    for p in sorted((ws / "deals").glob("*.md")):
        fm = frontmatter(p)
        fm["_path"] = p.relative_to(ws).as_posix()
        errors += [f"{fm['_path']}: {e}" for e in problems(fm)]
        deals.append(fm)
    product = frontmatter(ws / "product.md") if (ws / "product.md").is_file() else {}
    return deals, product, errors


def money(amount: float, currency: str) -> str:
    symbol = SYMBOLS.get(currency, f"{currency} " if currency else "")
    return f"{symbol}{amount:,.0f}"


def weight(deal: dict) -> float:
    override = number(deal.get("probability"))
    return (override if override is not None else PROBABILITY.get(deal.get("stage"), 0)) / 100


def render(deals: list[dict], product: dict, today: date) -> str:
    cur, iso = product.get("currency", ""), today.isoformat()
    lines = ["# Pipeline", "", f"<!-- Generated by go-to-market/scripts/deals.py on {iso}. Don't edit by hand. -->", ""]

    open_deals = sorted((d for d in deals if d.get("stage") in OPEN), key=lambda d: d.get("next_step_due") or "9999")
    lines += ["## Open deals", ""]
    if open_deals:
        lines += ["| Company | Stage | Value | Next step | Due | Close |", "|---|---|---|---|---|---|"]
        for d in open_deals:
            due, close = d.get("next_step_due", ""), d.get("close_date", "")
            value = number(d.get("value"))
            lines.append(f"| {d.get('company', '')} | {d['stage']} | {money(value, cur) if value is not None else ''} "
                         f"| {d.get('next_step', '')} | {due}{' ⚠️ overdue' if due and due < iso else ''} "
                         f"| {close}{' ⚠️ passed' if close and close < iso else ''} |")
    else:
        lines.append("None.")

    lines += ["", "## By stage", "", "| Stage | Deals | Value | Weighted |", "|---|---|---|---|"]
    total = weighted = 0.0
    for stage in OPEN:
        in_stage = [d for d in open_deals if d["stage"] == stage]
        value = sum(number(d.get("value")) or 0 for d in in_stage)
        w = sum((number(d.get("value")) or 0) * weight(d) for d in in_stage)
        total, weighted = total + value, weighted + w
        lines.append(f"| {stage} | {len(in_stage)} | {money(value, cur)} | {money(w, cur)} |")
    lines.append(f"| **open** | {len(open_deals)} | {money(total, cur)} | {money(weighted, cur)} |")
    target = number(product.get("quarter_target"))
    if target:
        lines += ["", f"Coverage: the open pipeline is {total / target:.1f}× the quarter target of {money(target, cur)}. "
                      "Founder-led sales usually needs about 3×."]

    attention = []
    for d in open_deals:
        name = d.get("company") or d["_path"]
        if d.get("next_step_due") and d["next_step_due"] < iso:
            attention.append(f"{name}: next step overdue since {d['next_step_due']}")
        if d.get("close_date") and d["close_date"] < iso:
            attention.append(f"{name}: close date {d['close_date']} has passed; update it or the stage")
        if d.get("updated") and DATE_RE.match(d["updated"]):
            age = (today - date.fromisoformat(d["updated"])).days
            if age > STALE_DAYS:
                attention.append(f"{name}: not updated for {age} days")
    parked = sorted((d for d in deals if d.get("stage") == "parked"), key=lambda d: d.get("next_step_due") or "9999")
    for d in parked:
        if d.get("next_step_due") and d["next_step_due"] <= iso:
            attention.append(f"{d.get('company') or d['_path']}: parked deal is due for a revisit ({d['next_step_due']})")
    lines += ["", "## Needs attention", ""] + ([f"- {a}" for a in attention] or ["Nothing."])

    if parked:
        lines += ["", "## Parked", "", "| Company | Revisit | Note |", "|---|---|---|"]
        lines += [f"| {d.get('company', '')} | {d.get('next_step_due', '')} | {d.get('next_step', '')} |" for d in parked]

    won = [d for d in deals if d.get("stage") == "won"]
    lost = [d for d in deals if d.get("stage") == "lost"]
    lines += ["", "## Closed (all time)", ""]
    if won or lost:
        won_value = sum(number(d.get("value")) or 0 for d in won)
        lines.append(f"Won: {len(won)} ({money(won_value, cur)}) · Lost: {len(lost)} · "
                     f"Win rate: {len(won) / (len(won) + len(lost)):.0%}")
        reasons: dict[str, int] = {}
        for d in lost:
            reason = d.get("loss_reason") or "not recorded"
            reasons[reason] = reasons.get(reason, 0) + 1
        if reasons:
            lines += ["", "Loss reasons: " + ", ".join(f"{r} {n}" for r, n in sorted(reasons.items(), key=lambda x: (-x[1], x[0])))]
    else:
        lines.append("No closed deals yet.")
    return "\n".join(lines) + "\n"


def self_test() -> int:
    def deal(name: str, body: str) -> None:
        (ws / "deals" / f"{name}.md").write_text(f"---\n{body}---\n\n## Log\n", encoding="utf-8")

    with tempfile.TemporaryDirectory() as tmp:
        ws = Path(tmp)
        (ws / "deals").mkdir()
        (ws / "product.md").write_text("---\nproduct: Test\ncurrency: EUR\nquarter_target: 30000   # hint\n---\n")
        deal("brightcart", "company: Brightcart\nstage: proposal\nsource: warm intro\nvalue: 12000\n"
                           "next_step: Review proposal with Jo\nnext_step_due: 2026-10-08\nclose_date: 2026-12-15\nupdated: 2026-10-10\n")
        deal("pixelwerk", "company: Pixelwerk\nstage: discovery\nsource: outbound\nvalue: 8000\nnext_step: Demo\n"
                          "next_step_due: 2026-10-20\nclose_date: 2026-09-30\nupdated: 2026-09-20\n")
        deal("acme", "company: Acme\nstage: won\nsource: inbound\nvalue: 6000\nupdated: 2026-10-01\n")
        deal("zeta", "company: Zeta\nstage: lost\nsource: outbound\nloss_reason: price\nupdated: 2026-10-02\n")
        deal("bad", "company: Bad\nstage: lost\nsource: cold\nupdated: 2026-10-02\nloss_reason:              # hint\n")
        deal("later", "company: Later\nstage: parked\nsource: event\nnext_step: Revisit after their budget round\n"
                      "next_step_due: 2027-01-15\nupdated: 2026-10-01\n")
        deals, product, errors = load(ws)
        md = render(deals, product, date(2026, 10, 13))
        checks = [
            len(deals) == 6,
            any("bad.md: source 'cold'" in e for e in errors),
            any("bad.md: lost deals need 'loss_reason'" in e for e in errors),
            not any("brightcart" in e or "later" in e or "acme" in e for e in errors),
            "| Brightcart | proposal | €12,000 | Review proposal with Jo | 2026-10-08 ⚠️ overdue | 2026-12-15 |" in md,
            "| Pixelwerk | discovery | €8,000 | Demo | 2026-10-20 | 2026-09-30 ⚠️ passed |" in md,
            "| **open** | 2 | €20,000 | €8,000 |" in md,
            "0.7× the quarter target of €30,000" in md,
            "Pixelwerk: not updated for 23 days" in md,
            "| Later | 2027-01-15 | Revisit after their budget round |" in md,
            "Won: 1 (€6,000) · Lost: 2 · Win rate: 33%" in md,
            "Loss reasons: not recorded 1, price 1" in md,
        ]
    print("deals self-test:", "ok" if all(checks) else f"FAILED {checks}\n{errors}\n{md}")
    return 0 if all(checks) else 1


def main() -> int:
    ap = argparse.ArgumentParser(description="Validate a go-to-market workspace and regenerate pipeline.md.")
    ap.add_argument("workspace", nargs="?", type=Path)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    if args.self_test:
        return self_test()
    if not args.workspace:
        ap.error("give the workspace folder")
    deals, product, errors = load(args.workspace)
    for e in errors:
        print(f"error: {e}")
    if args.write and not errors:
        (args.workspace / "pipeline.md").write_text(render(deals, product, date.today()), encoding="utf-8")
        print(f"wrote {args.workspace / 'pipeline.md'}")
    n_open = sum(1 for d in deals if d.get("stage") in OPEN)
    print(f"{'FAILED' if errors else 'ok'}: {len(deals)} deals ({n_open} open), {len(errors)} errors")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
