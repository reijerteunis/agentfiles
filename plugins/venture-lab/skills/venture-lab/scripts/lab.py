#!/usr/bin/env python3
"""Validate a venture-lab workspace and regenerate its pipeline.md. Standard library only.

Usage:
  python3 lab.py <workspace> --check     validate every ideas/*/idea.md, exit 1 on errors
  python3 lab.py <workspace> --write     validate, then rewrite <workspace>/pipeline.md
  python3 lab.py --self-test

Also reports experiments whose end date has passed without a recorded result.
"""

from __future__ import annotations

import argparse
import re
import sys
import tempfile
from datetime import date
from pathlib import Path

STAGES = ["capture", "explore", "validate", "decide", "prepare"]
STATUSES = ["active", "parked", "killed", "launched"]
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def frontmatter(path: Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return {}
    out = {}
    for line in text[4:].split("\n---", 1)[0].splitlines():
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*?)\s*(#.*)?$", line)
        if m:
            out[m.group(1)] = m.group(2).strip().strip('"').strip("'")
    return out


def load(ws: Path, today: date) -> tuple[list[dict], list[str], list[str]]:
    ideas, errors, stale = [], [], []
    for p in sorted((ws / "ideas").glob("*/idea.md")):
        fm = frontmatter(p)
        fm["_slug"] = p.parent.name
        rel = p.relative_to(ws).as_posix()
        if fm.get("stage") not in STAGES:
            errors.append(f"{rel}: stage '{fm.get('stage')}' not in {STAGES}")
        if fm.get("status") not in STATUSES:
            errors.append(f"{rel}: status '{fm.get('status')}' not in {STATUSES}")
        for key in ("decide_by", "created"):
            if fm.get(key) and not DATE_RE.match(fm[key]):
                errors.append(f"{rel}: '{key}' must be YYYY-MM-DD, got '{fm[key]}'")
        if fm.get("status") == "active":
            for key in ("next_step", "decide_by"):
                if not fm.get(key):
                    errors.append(f"{rel}: active ideas need '{key}'")
        for exp in sorted((p.parent / "experiments").glob("*.md")):
            efm = frontmatter(exp)
            if efm.get("end") and DATE_RE.match(efm["end"]) and efm["end"] < today.isoformat() and not efm.get("result"):
                stale.append(f"{exp.relative_to(ws).as_posix()}: ended {efm['end']}, no result recorded")
        ideas.append(fm)
    return ideas, errors, stale


def render(ideas: list[dict], stale: list[str], today: date) -> str:
    lines = ["# Venture pipeline", "", f"<!-- Generated by venture-lab/scripts/lab.py on {today.isoformat()}. Don't edit by hand. -->", ""]
    active = sorted((i for i in ideas if i.get("status") == "active"), key=lambda i: i.get("decide_by") or "9999")
    lines += ["## Active", ""]
    if active:
        lines += ["| Idea | Stage | Score | Riskiest assumption | Next step | Decide by |", "|---|---|---|---|---|---|"]
        for i in active:
            due = i.get("decide_by", "")
            flag = " ⚠️ overdue" if due and due < today.isoformat() else ""
            lines.append(f"| {i.get('title', i['_slug'])} | {i.get('stage','')} | {i.get('screen_score','')} | "
                         f"{i.get('riskiest_assumption','')} | {i.get('next_step','')} | {due}{flag} |")
    else:
        lines.append("No active ideas.")
    if stale:
        lines += ["", "## Experiments waiting for a result", ""] + [f"- {s}" for s in stale]
    closed = [i for i in ideas if i.get("status") in ("parked", "killed", "launched")]
    if closed:
        lines += ["", "## Parked, killed and launched", "", "| Idea | Status | Stage reached |", "|---|---|---|"]
        lines += [f"| {i.get('title', i['_slug'])} | {i.get('status')} | {i.get('stage','')} |" for i in closed]
    lines += ["", f"Ideas: {len(ideas)} total, {len(active)} active, {sum(1 for i in ideas if i.get('status') == 'killed')} killed."]
    return "\n".join(lines) + "\n"


def self_test() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        ws = Path(tmp)
        good = ws / "ideas" / "invoice-ai"
        (good / "experiments").mkdir(parents=True)
        (good / "idea.md").write_text("---\ntitle: Invoice AI\nstage: validate\nstatus: active\nscreen_score: 62  # from idea-screen\n"
                                      "riskiest_assumption: \"They will pay\"\nnext_step: smoke test\ndecide_by: 2026-11-01\n---\n")
        (good / "experiments" / "01-smoke.md").write_text("---\nend: 2026-10-10\nresult:\n---\n")
        bad = ws / "ideas" / "bad"
        bad.mkdir(parents=True)
        (bad / "idea.md").write_text("---\ntitle: Bad\nstage: dreaming\nstatus: active\n---\n")
        ideas, errors, stale = load(ws, date(2026, 10, 14))
        md = render(ideas, stale, date(2026, 10, 14))
        checks = [len(ideas) == 2, any("stage 'dreaming'" in e for e in errors),
                  any("active ideas need 'next_step'" in e for e in errors), len(stale) == 1,
                  "| Invoice AI | validate | 62 | They will pay | smoke test | 2026-11-01 |" in md]
    print("lab self-test:", "ok" if all(checks) else f"FAILED {checks}\n{errors}\n{md}")
    return 0 if all(checks) else 1


def main() -> int:
    ap = argparse.ArgumentParser(description="Validate a venture-lab workspace and regenerate pipeline.md.")
    ap.add_argument("workspace", nargs="?", type=Path)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    if args.self_test:
        return self_test()
    if not args.workspace:
        ap.error("give the workspace folder")
    ideas, errors, stale = load(args.workspace, date.today())
    for e in errors:
        print(f"error: {e}")
    for s in stale:
        print(f"result missing: {s}")
    if args.write and not errors:
        (args.workspace / "pipeline.md").write_text(render(ideas, stale, date.today()), encoding="utf-8")
        print(f"wrote {args.workspace / 'pipeline.md'}")
    print(f"{'FAILED' if errors else 'ok'}: {len(ideas)} ideas, {len(errors)} errors, {len(stale)} results missing")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
